"""Actual two-step not-found upload, analysis and managed search on temporary DB."""
import io
from openpyxl import Workbook
from playwright.sync_api import Page, expect
from test_corrections_browser import prepare


def test_not_found_upload_analysis_resume_coverage_search_and_category_isolation(page: Page, servers: tuple[str, str]) -> None:
    prepare(servers[1], candidates=2)
    book = Workbook()
    sheet = book.active
    sheet.title = "Tidak Ketemu"
    sheet.append(["objectid", "idpelanggan", "namapelanggan", "latitudey", "longitudex", "nokwhmeter", "idtitik", "daya"])
    sheet.append([101, "001", "Already PDPJ", -9, 110, None, None, None])
    sheet.append([102, "000222", "Search target", -6.2, 106.8, "M1", "S1", "bad"])
    sheet.append([103, "333", "Invalid coordinate", 95, 106.8, None, None, None])
    data = io.BytesIO()
    book.save(data)
    page.goto("/koreksi/idpel-tidak-ketemu")
    page.get_by_role("link", name="Unggah data", exact=True).click()
    expect(page.get_by_role("heading", name="Unggah Data", exact=True)).to_be_visible()
    expect(page.locator(".geo-topbar").get_by_label("Judul fitur", exact=True)).to_have_text("IDPEL Tidak Ketemu")
    page.get_by_label("Berkas IDPEL Tidak Ketemu", exact=True).set_input_files({"name": "not-found.xlsx", "mimeType": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "buffer": data.getvalue()})
    select = page.get_by_label("Pilih sheet atau tabel", exact=True)
    expect(select).to_be_visible()
    expect(page.get_by_role("table", name="Tabel asli", exact=True)).to_have_count(0)
    select.select_option("Tidak Ketemu")
    expect(page.get_by_role("table", name="Tabel asli", exact=True)).to_contain_text("000222")
    page.get_by_role("button", name="Simpan dan berikutnya", exact=True).click()
    expect(page.get_by_role("heading", name="Analisis radius", exact=True)).to_be_visible()
    expect(page.get_by_role("button", name="Lihat hasil", exact=True)).to_be_disabled()
    page.get_by_role("link", name="Kembali ke IDPEL Tidak Ketemu", exact=True).click()
    work = page.get_by_role("region", name="Proses IDPEL Tidak Ketemu belum selesai", exact=True)
    expect(work).to_contain_text("3 baris sudah disimpan")
    work.get_by_role("link", name="Lanjutkan proses", exact=True).click()
    page.reload()
    page.get_by_role("button", name="Mulai analisis", exact=True).click()
    expect(page.get_by_text("Analisis selesai", exact=True)).to_be_visible(timeout=25000)
    radius = page.get_by_label("Radius pencarian", exact=True)
    expect(radius).to_have_value("5")
    coverage = page.get_by_role("heading", name="Perkiraan cakupan", exact=True).locator("..")
    expect(coverage.get_by_role("definition")).to_have_text(["1", "0", "1", "1"])
    page.get_by_role("link", name="Kembali ke IDPEL Tidak Ketemu", exact=True).click()
    cards = page.get_by_role("region", name="Ringkasan IDPEL Tidak Ketemu", exact=True)
    expect(cards.get_by_text("IDPEL Sudah Ada di PDPJ", exact=True).locator("..").locator("span").last).to_have_text("1")
    blocked = page.get_by_role("table").get_by_role("row").filter(has_text="Already PDPJ")
    blocked.get_by_role("link", name="Detail", exact=True).click()
    expect(page.get_by_role("region", name="IDPEL Sudah Ada di PDPJ", exact=True)).to_contain_text("001")
    page.reload()
    expect(page.get_by_role("region", name="IDPEL Sudah Ada di PDPJ", exact=True)).to_be_visible()
    page.get_by_role("link", name="Kembali ke IDPEL Tidak Ketemu", exact=True).click()
    work.get_by_role("link", name="Lanjutkan proses", exact=True).click()
    expect(radius).to_have_value("5")
    page.get_by_role("button", name="Sebelumnya", exact=True).click()
    expect(page.get_by_role("table", name="Tabel asli", exact=True)).to_contain_text("000222")
    page.get_by_role("button", name="Berikutnya", exact=True).click()
    expect(radius).to_have_value("5")
    radius.fill("0")
    expect(page.get_by_role("button", name="Mulai pencarian kandidat", exact=True)).to_be_disabled()
    radius.fill("5")
    page.get_by_role("button", name="Mulai pencarian kandidat", exact=True).click()
    results = page.get_by_role("button", name="Lihat hasil", exact=True)
    expect(results).to_be_enabled(timeout=25000)
    progress = page.get_by_role("region", name="Pencarian kandidat", exact=True)
    expect(progress.get_by_text("IDPEL Sudah Ada di PDPJ", exact=True).locator("..")).to_contain_text("1")
    page.reload()
    expect(radius).to_be_disabled()
    expect(results).to_be_enabled()
    results.click()
    table = page.get_by_role("table")
    expect(table.get_by_role("cell", name="000222", exact=True)).to_be_visible()
    expect(table.get_by_role("row").filter(has_text="Already PDPJ")).to_contain_text("IDPEL Sudah Ada di PDPJ")
    expect(work).to_have_count(0)
    page.get_by_role("navigation", name="Kategori data koreksi", exact=True).get_by_role("link", name="IDPEL Kosong", exact=True).click()
    summary = page.get_by_role("region", name="Ringkasan IDPEL Kosong", exact=True)
    expect(summary.get_by_text("Total Data", exact=True).locator("..").locator("span").last).to_have_text("0")
