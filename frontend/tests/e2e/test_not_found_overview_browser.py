"""Phase-one not-found UI against temporary test services and stored results."""
from pathlib import Path
from playwright.sync_api import Page, expect
from test_corrections_browser import prepare, upload, launch


def test_not_found_empty_home_cards_and_existing_upload_access(page: Page) -> None:
    page.goto("/koreksi/idpel-tidak-ketemu")
    cards = page.get_by_role("region", name="Ringkasan IDPEL Tidak Ketemu", exact=True)
    expect(cards.locator(":scope > div")).to_have_count(6)
    assert cards.evaluate("element => getComputedStyle(element).gridTemplateColumns.split(' ').length") == 3
    expect(cards.get_by_text("IDPEL Sudah Ada di PDPJ", exact=True)).to_be_visible()
    expect(page.get_by_role("alert")).to_have_count(0)
    expect(page.get_by_role("columnheader", name="IDPEL", exact=True)).to_be_visible()
    expect(page.locator(".geo-topbar").get_by_role("navigation", name="Jejak halaman")).to_have_count(0)
    page.get_by_role("link", name="Unggah data", exact=True).click()
    expect(page.locator("input[type=file]")).to_be_attached()
    expect(page.locator(".geo-topbar").get_by_label("Halaman aktif", exact=True)).to_have_text("Unggah Data")
    page.goto("/koreksi/idpel-tidak-ketemu")
    page.set_viewport_size({"width": 390, "height": 844})
    expect(cards).to_be_visible()
    assert cards.evaluate("element => getComputedStyle(element).gridTemplateColumns.split(' ').length") == 1
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")


def test_not_found_saved_status_detail_candidates_and_resume(page: Page, servers: tuple[str, str], tmp_path: Path) -> None:
    prepare(servers[1], candidates=13)
    batch = upload(servers[1], "idpel_tidak_ketemu", "objectid,IDPEL,NAMA,LAT,LON,NOAGENDA\n701,001,IDPEL PDPJ,-6.2,106.8,A1\n702,222,Pelanggan target,-6.2,106.8,A2\n703,333,Koordinat kosong,,,A3\n704,444,Jauh,-9,110,A4\n")
    page.goto(f"/koreksi/idpel-tidak-ketemu?workspace=1&batch_id={batch}")
    launch(page)
    page.goto("/koreksi/idpel-tidak-ketemu")
    cards = page.get_by_role("region", name="Ringkasan IDPEL Tidak Ketemu", exact=True)
    expect(cards.get_by_text("IDPEL Sudah Ada di PDPJ", exact=True).locator("..").locator("span").last).to_have_text("1")
    table = page.get_by_role("table")
    expect(table.get_by_role("columnheader")).to_have_text(["No", "Objek ID", "Nomor agenda", "IDPEL", "Nama pelanggan", "Koordinat X", "Koordinat Y", "Status", "Kandidat", "Aksi"])
    page.get_by_label("Filter status IDPEL Tidak Ketemu", exact=True).select_option("idpel_in_pdpj")
    expect(table.get_by_role("row")).to_have_count(2)
    table.get_by_role("link", name="Detail", exact=True).click()
    expect(page.locator(".geo-topbar").get_by_label("Judul fitur", exact=True)).to_have_text("IDPEL Tidak Ketemu")
    expect(page.locator(".geo-topbar").get_by_label("Halaman aktif", exact=True)).to_have_text("Detail Data")
    evidence = page.get_by_role("region", name="IDPEL Sudah Ada di PDPJ", exact=True)
    expect(evidence).to_contain_text("001")
    expect(page.get_by_role("region", name="Daftar kandidat", exact=True)).to_contain_text("pencarian kandidat tidak dijalankan")
    page.reload()
    expect(evidence).to_be_visible()
    page.get_by_role("link", name="Kembali ke IDPEL Tidak Ketemu", exact=True).click()
    page.get_by_label("Cari IDPEL Tidak Ketemu", exact=True).fill("222")
    expect(table.get_by_role("row")).to_have_count(2)
    table.get_by_role("link", name="Detail", exact=True).click()
    data = page.get_by_role("region", name="Data pelanggan", exact=True)
    expect(data).to_contain_text("222")
    expect(data).to_contain_text("Pelanggan target")
    candidates = page.get_by_role("region", name="Daftar kandidat", exact=True)
    expect(candidates.get_by_role("row")).to_have_count(11)
    candidates.get_by_label("Kandidat per halaman", exact=True).select_option("5")
    expect(candidates.get_by_role("row")).to_have_count(6)
    candidates.get_by_role("button", name="Halaman kandidat berikutnya", exact=True).click()
    expect(candidates.get_by_role("row").nth(1).get_by_role("cell").first).to_have_text("6")
    candidates.get_by_label("Urutan jarak kandidat", exact=True).click()
    expect(candidates.get_by_role("row").nth(1).get_by_role("cell").first).to_have_text("1")
    candidates.get_by_role("button", name="Detail sumber kandidat", exact=False).first.click()
    popup = page.get_by_role("dialog", name="Detail Sumber Kandidat", exact=True)
    expect(popup).to_contain_text("dil.csv")
    page.keyboard.press("Escape")
    expect(popup).to_have_count(0)
    page.locator(".geo-topbar").get_by_role("link", name="IDPEL Tidak Ketemu", exact=True).click()
    page.screenshot(path=str(tmp_path / "not-found-overview.png"), full_page=True)
    print("UI_SCREENSHOT", tmp_path / "not-found-overview.png")
    # A confirmed import without a run remains reachable using the existing workspace.
    pending_batch = upload(servers[1], "idpel_tidak_ketemu", "IDPEL,NAMA,LAT,LON\n000777,Tersimpan belum diproses,-6.2,106.8\n")
    page.get_by_role("button", name="Muat ulang IDPEL Tidak Ketemu", exact=True).click()
    work = page.get_by_role("region", name="Proses IDPEL Tidak Ketemu belum selesai", exact=True)
    expect(work).to_contain_text("1 baris")
    work.get_by_role("link", name="Lanjutkan proses", exact=True).click()
    expect(page).to_have_url(f"{servers[0]}/koreksi/idpel-tidak-ketemu?flow=upload&batch_id={pending_batch}")
